#!/usr/bin/env python3
"""test/load/stress: writes one baresip configuration directory (config + accounts) for a slice
of the tenant's devices, standing in for Ringotel softphones (docs/spec.md §10.4 "Branch
provision profile": `protocol: sips`, `nosrtp: false`, Opus).

Every account registers over TLS to zamfono:5061 (compose.stress.yaml maps that name, the
CN of the stack's placeholder certificate, to asterisk; the certificate itself is the CA file,
so baresip verifies the server the way a real softphone would), auto-answers, offers/accepts only Opus and
requires SDES-SRTP (`mediaenc=srtp-mand`, i.e. RTP/SAVP with a=crypto), which is what the
rendered endpoint of a `tls` device demands (packages/api/src/lib/server/pjsip/render.ts:
`media_encryption = sdes`). Audio comes from a WAV file (aufile), so each answered call encodes
real speech into Opus (complexity 0: the generator shares the host with the stack, so its own
encoder is kept cheap; Asterisk's Opus encoder settings are untouched); what the device receives
is decoded and discarded. Answering one account's call holds none of the process's others
(`call_hold_other_calls no`). ctrl_tcp (port sip_port - 1080) is how devices_ctrl.py ends the
calls from the device side and has the accounts register anew (`regint=600` below).

Usage: gen_baresip.py <creds.csv> <out_dir> <first_index> <count> <sip_port> <wav_path>
         [<kind> [<registrar> [<cafile> [<account_extra>]]]]
creds.csv lines: "<sip_username>,<sip_password>[,<answermode>]" (one per device, in user order;
answermode defaults to auto). test/load/density's devices pass the optional rest:
  kind           opus (default: Opus + mandatory SDES-SRTP), alaw (G.711 A-law) or g722 -- the one
                 codec the device offers and accepts; the source WAV must be at its rate
  registrar      the account's host part, default `zamfono:5061;transport=tls`; SRTP is mandated
                 only on a TLS registrar
  cafile         sip_cafile, default /load-gen/asterisk-ca.pem
  account_extra  appended to every account line (e.g. `;outbound="sip:<ip>:5061;transport=tls"`)
"""
import sys
from pathlib import Path

# kind: (codec modules, source and playback rate)
KINDS = {'opus': (('opus.so', 'srtp.so'), 48000), 'alaw': (('g711.so',), 8000),
         'g722': (('g722.so',), 16000)}

CONFIG = '''# generated by test/load/stress/gen_baresip.py
poll_method		epoll
sip_listen		0.0.0.0:{port}
rtp_ports		20000-60000
sip_cafile		{cafile}
dns_getaddrinfo		yes
call_local_timeout	120
call_max_calls		{max_calls}
call_hold_other_calls	no
audio_player		aufile,/dev/null
audio_source		aufile,{wav}
audio_alert		aufile,/dev/null
audio_level		no
ausrc_srate		{srate}
auplay_srate		{srate}
ausrc_channels		1
auplay_channels		1
audio_buffer		20-160
rtp_tos			184
rtp_ports		40000-49999
rtp_stats		yes
jitter_buffer_delay	5-10
opus_bitrate		28000
opus_complexity		0
opus_stereo		no
opus_sprop_stereo	no
module_path		/usr/lib/baresip/modules
{modules}module			aufile.so
module_app		account.so
module_app		menu.so
module_app		contact.so
module_app		ctrl_tcp.so
ctrl_tcp_listen		127.0.0.1:{ctrl}
'''


def main() -> None:
    creds_path, out_dir, first, count, port, wav = sys.argv[1:7]
    kind, registrar, cafile, extra = (sys.argv[7:] + ['opus', 'zamfono:5061;transport=tls',
                                                      '/load-gen/asterisk-ca.pem', ''][len(sys.argv[7:]):])
    first, count = int(first), int(count)
    modules, srate = KINDS[kind]
    mediaenc = 'mediaenc=srtp-mand;' if 'transport=tls' in registrar else ''
    rows = [line.strip().split(',') for line in Path(creds_path).read_text().splitlines()
            if line.strip()]
    rows = rows[first:first + count]
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / 'config').write_text(CONFIG.format(
        port=port, wav=wav, ctrl=int(port) - 5080 + 4000, cafile=cafile, srate=srate,
        max_calls=max(4, len(rows) * 2), modules=''.join(f'module\t\t\t{m}\n' for m in modules)))
    (out / 'contacts').write_text('')
    accounts = [
        f'<sip:{row[0]}@{registrar}>;auth_pass={row[1]};'
        f'answermode={row[2] if len(row) > 2 else "auto"};{mediaenc}regint=600;ptime=20{extra}'
        for row in rows
    ]
    (out / 'accounts').write_text('\n'.join(accounts) + '\n')
    print(f'{out}: {len(accounts)} accounts', file=sys.stderr)


if __name__ == '__main__':
    main()
